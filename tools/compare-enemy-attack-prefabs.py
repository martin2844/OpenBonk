#!/usr/bin/env python3
"""Compare object hierarchies referenced by decoded enemy special attacks.

Inputs are local APK/OBB pairs and enemy inventories generated by
extract-unity-weapon-data.py --kind enemy. The private report compares names,
active state, layers, local transforms and component types including MonoScript
identities, plus non-pointer fields on box and mesh colliders and rigidbodies.
Other component fields, assets, code and combat are not compared.
Requires UnityPy.
"""
import argparse
from collections import Counter
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import zipfile

import UnityPy

ROOT = Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location('build_inventory', ROOT / 'tools/compare-unity-build-content.py')
inventory = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inventory)
PHYSICS_TYPES = frozenset(('BoxCollider', 'MeshCollider', 'Rigidbody'))


def without_pointers(value):
    if isinstance(value, dict):
        if set(value) == {'m_FileID', 'm_PathID'}:
            return {'$unity_pointer': True}
        return {key: without_pointers(item) for key, item in value.items()}
    if isinstance(value, list):
        return [without_pointers(item) for item in value]
    return value


def targets(document):
    if document.get('schema') != 1 or document.get('unity_version') != '2023.2.22f1':
        raise ValueError('unsupported enemy inventory')
    rows = document.get('enemies')
    if not isinstance(rows, list) or len(rows) != 53:
        raise ValueError('unexpected enemy count')
    result, seen = {}, set()
    for row in rows:
        data, external = row['data'], row['external_files']
        name, attacks = data['m_Name'], data['specialAttacks']
        if not isinstance(name, str) or not name or name in seen or not isinstance(attacks, list) or not isinstance(external, list):
            raise ValueError('invalid enemy identity or attacks')
        seen.add(name)
        for index, attack in enumerate(attacks):
            pointer = attack['attackPrefab']
            file_id, path_id = pointer['m_FileID'], pointer['m_PathID']
            if type(file_id) is not int or type(path_id) is not int:
                raise ValueError('invalid prefab pointer')
            if file_id == 0 and path_id == 0:
                result[(name, index)] = {'attack': attack['attackName'], 'target': None}
                continue
            if file_id == 0:
                group = row['source_group']
            elif 0 < file_id <= len(external):
                group = external[file_id - 1]
            else:
                raise ValueError('unresolved prefab file')
            if not isinstance(group, str):
                raise ValueError('invalid prefab group')
            result[(name, index)] = {'attack': attack['attackName'], 'group': group, 'path_id': path_id}
    return result


def read_build(apk, obb, document, temp_root):
    hashes = []
    for path in (apk, obb):
        with path.open('rb') as stream:
            hashes.append(hashlib.file_digest(stream, 'sha256').hexdigest())
    if document.get('input_sha256') != hashes:
        raise ValueError('enemy inventory does not match APK/OBB inputs')
    result = targets(document)
    selected = {'globalgamemanagers.assets'} | {row['group'] for row in result.values() if 'group' in row}
    files = {}
    for path in (apk, obb):
        with zipfile.ZipFile(path) as archive:
            for name, parts in inventory.asset_groups(archive).items():
                if name not in selected:
                    continue
                if name in files:
                    raise ValueError('duplicate serialized group')
                files[name] = b''.join(archive.read(part) for part in parts)
    if set(files) != selected:
        raise ValueError('required serialized group missing')
    with tempfile.TemporaryDirectory(prefix='openbonk-attack-roots-', dir=temp_root) as temp:
        paths = []
        for name, raw in files.items():
            path = Path(temp) / name
            path.write_bytes(raw)
            paths.append(str(path))
        env = UnityPy.load(*paths)
        objects = {(obj.assets_file.name, obj.path_id): obj for obj in env.objects}

        def describe(group, path_id, visited, depth):
            if depth > 128 or len(visited) >= 10000 or (group, path_id) in visited:
                raise ValueError('cyclic or oversized attack hierarchy')
            visited.add((group, path_id))
            obj = objects.get((group, path_id))
            if obj is None or obj.type.name != 'GameObject' or obj.assets_file.unity_version != '2023.2.22f1':
                raise ValueError('unresolved or unsupported attack object')
            game_object = obj.read()
            components, physics, transform = [], [], None
            for item in game_object.m_Component:
                pointer = item.component
                if pointer.file_id != 0:
                    raise ValueError('external object component')
                component = objects.get((group, pointer.path_id))
                if component is None:
                    raise ValueError('unresolved object component')
                identity = [component.type.name]
                if component.type.name == 'MonoBehaviour':
                    script = component.parse_monobehaviour_head().m_Script.deref_parse_as_object()
                    identity.extend((script.m_AssemblyName, script.m_Namespace, script.m_ClassName))
                if component.type.name in ('Transform', 'RectTransform'):
                    if transform is not None:
                        raise ValueError('multiple transforms on object')
                    transform = component.read()
                if component.type.name in PHYSICS_TYPES:
                    physics.append({'index': len(components), 'type': component.type.name,
                                    'fields': without_pointers(component.read_typetree())})
                components.append(identity)
            if transform is None:
                raise ValueError('missing transform')
            children = []
            for pointer in transform.m_Children:
                if pointer.file_id != 0:
                    raise ValueError('external child transform')
                child = objects.get((group, pointer.path_id))
                if child is None or child.type.name not in ('Transform', 'RectTransform'):
                    raise ValueError('unresolved child transform')
                owner = child.read().m_GameObject
                if owner.file_id != 0:
                    raise ValueError('external child owner')
                children.append(describe(group, owner.path_id, visited, depth + 1))
            pos, rot, scale = transform.m_LocalPosition, transform.m_LocalRotation, transform.m_LocalScale
            return {'name': game_object.m_Name, 'active': game_object.m_IsActive, 'layer': game_object.m_Layer,
                    'local_position': [pos.x, pos.y, pos.z], 'local_rotation': [rot.x, rot.y, rot.z, rot.w],
                    'local_scale': [scale.x, scale.y, scale.z], 'components': components,
                    'physics': physics, 'children': children}

        for key, row in result.items():
            if 'group' not in row:
                continue
            group, path_id = row['group'], row['path_id']
            hierarchy = describe(group, path_id, set(), 0)
            result[key] = {'attack': row['attack'], 'target': hierarchy['name'], 'hierarchy': hierarchy}
    return result


def compare(reference, candidate):
    keys = reference.keys() | candidate.keys()
    differences = [{'enemy': key[0], 'index': key[1], 'reference': reference.get(key), 'candidate': candidate.get(key)}
                   for key in sorted(keys) if reference.get(key) != candidate.get(key)]
    def object_count(hierarchy):
        return 1 + sum(object_count(child) for child in hierarchy['children'])
    def physics_counts(rows):
        counts = Counter()
        def visit(hierarchy):
            counts.update(item['type'] for item in hierarchy.get('physics', []))
            for child in hierarchy['children']:
                visit(child)
        for row in rows.values():
            if 'hierarchy' in row:
                visit(row['hierarchy'])
        return dict(sorted(counts.items()))
    return {'reference_attacks': len(reference), 'candidate_attacks': len(candidate),
            'reference_nonnull': sum(row['target'] is not None for row in reference.values()),
            'candidate_nonnull': sum(row['target'] is not None for row in candidate.values()),
            'reference_object_occurrences': sum(object_count(row['hierarchy']) for row in reference.values() if 'hierarchy' in row),
            'candidate_object_occurrences': sum(object_count(row['hierarchy']) for row in candidate.values() if 'hierarchy' in row),
            'reference_physics_occurrences': physics_counts(reference),
            'candidate_physics_occurrences': physics_counts(candidate),
            'differences': differences}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for side in ('reference', 'candidate'):
        for name in ('apk', 'obb', 'enemies'):
            parser.add_argument('--' + side + '-' + name, type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    inputs = []
    for side in ('reference', 'candidate'):
        for name in ('apk', 'obb', 'enemies'):
            path = getattr(args, side + '_' + name).expanduser()
            if path.is_symlink() or not path.is_file():
                parser.error('inputs must be regular files')
            inputs.append(path.resolve())
    output = args.output.expanduser().absolute()
    if output.exists() or output.is_symlink() or not output.parent.is_dir():
        parser.error('output must be new')
    output = output.parent.resolve() / output.name
    if output.is_relative_to(ROOT) or output in inputs:
        parser.error('output must be separate from checkout and inputs')
    reference = read_build(*inputs[:2], json.loads(inputs[2].read_text(encoding='utf-8')), output.parent)
    candidate = read_build(*inputs[3:5], json.loads(inputs[5].read_text(encoding='utf-8')), output.parent)
    result = compare(reference, candidate)
    result['schema'] = 1
    result['input_sha256'] = []
    for path in inputs:
        with path.open('rb') as stream:
            result['input_sha256'].append(hashlib.file_digest(stream, 'sha256').hexdigest())
    result['limitations'] = 'Names, active states, layers, local transforms, component identities and non-pointer box/mesh collider and rigidbody fields only; other fields, references, assets, code and behavior are not compared.'
    with output.open('x', encoding='utf-8') as stream:
        json.dump(result, stream, ensure_ascii=False, indent=2)
        stream.write('\n')
    print('Compared', result['reference_attacks'], 'special attacks; differences:', len(result['differences']), '. Report remains private.')


if __name__ == '__main__':
    main()
