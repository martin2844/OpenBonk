using System;
using System.Collections.Generic;
using System.Reflection;
using System.Runtime.Serialization;
using Assets.Scripts.Actors.Player;
using Assets.Scripts.Actors;
using Assets.Scripts.Actors.Enemies;
using Assets.Scripts.Game.Combat;
using Assets.Scripts.Inventory__Items__Pickups;
using Assets.Scripts.Inventory__Items__Pickups.Items;
using Assets.Scripts.Inventory__Items__Pickups.Stats;
using Assets.Scripts.Inventory__Items__Pickups.Weapons;
using Assets.Scripts.Menu.Shop;
using Assets.Scripts.Player.Movement;
using Assets.Scripts.Utility;
using Inventory__Items__Pickups.Xp_and_Levels;
using UnityEditor;
using UnityEngine;

public static class BasicStatItemsPortCheck
{
    static void Near(float actual, float expected, string message) { if (Mathf.Abs(actual - expected) > .0001f) throw new Exception(message + ": " + actual + " expected " + expected); }
    static void Require(bool value, string message) { if (!value) throw new Exception(message); }
    public static void Run()
    {
        var root = new GameObject("basic stat items test"); root.SetActive(false);
        var player = root.AddComponent<MyPlayer>(); MyPlayer.Instance = player; GameManager.Instance = root.AddComponent<GameManager>();
        var data = root.AddComponent<DataManager>(); DataManager.Instance = data;
        var inventory = (PlayerInventory)FormatterServices.GetUninitializedObject(typeof(PlayerInventory)); player.inventory = inventory;
        inventory.characterData = AssetDatabase.LoadAssetAtPath<CharacterData>("Assets/MonoBehaviour/Fox.asset");
        inventory.tomeInventory = new TomeInventory(); inventory.itemInventory = new ItemInventory(); inventory.statusEffects = new PlayerStatusEffects(); inventory.statInventory = new StatInventory(); inventory.playerXp = new PlayerXp { level = 1 };
        inventory.playerStats = new PlayerStatsNew(inventory, true);
        var allItems = (Dictionary<EItem, ItemData>)typeof(DataManager).GetField("itemData", BindingFlags.Instance | BindingFlags.NonPublic).GetValue(data);
        var names = new[] { "Battery", "Clover", "Backpack", "Oats", "ForbiddenJuice", "GymSauce" };
        var ids = new[] { EItem.Battery, EItem.Clover, EItem.Backpack, EItem.Oats, EItem.ForbiddenJuice, EItem.GymSauce };
        var stats = new[] { EStat.AttackSpeed, EStat.Luck, EStat.Projectiles, EStat.MaxHealth, EStat.CritChance, EStat.DamageMultiplier };
        var perStack = new[] { .08f, .1f, 1f, 25f, .1f, .1f };
        var baseline = new float[stats.Length];
        float oldTime = MyTime.time;
        try
        {
            for (int i = 0; i < names.Length; i++)
            {
                var asset = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/" + names[i] + ".asset");
                Require(asset != null && asset.eItem == ids[i], "original " + names[i] + " asset");
                allItems.Add(ids[i], asset); baseline[i] = inventory.playerStats.GetStat(stats[i]);
                inventory.itemInventory.AddItem(ids[i], 2);
            }
            inventory.playerStats.Tick();
            for (int i = 0; i < names.Length; i++) Near(inventory.playerStats.GetStat(stats[i]), baseline[i] + 2f * perStack[i], names[i] + " two stacks");
            Near(WeaponUtility.GetCritChance(null), baseline[4] + .2f, "two ForbiddenJuice stacks reach crit calculation");
            var damageMethod = typeof(WeaponUtility).GetMethod("GetNewDamage", BindingFlags.Static | BindingFlags.NonPublic);
            Require(damageMethod != null, "weapon damage calculation");
            Near((float)damageMethod.Invoke(null, new object[] { 100f, new StatComponents() }), 100f * (baseline[5] + .2f), "two GymSauce stacks reach damage calculation");
            foreach (var id in ids) inventory.itemInventory.RemoveItem(id);
            inventory.playerStats.Tick();
            for (int i = 0; i < names.Length; i++) Near(inventory.playerStats.GetStat(stats[i]), baseline[i] + perStack[i], names[i] + " one stack");
            foreach (var id in ids) inventory.itemInventory.RemoveItem(id);
            inventory.playerStats.Tick();
            for (int i = 0; i < names.Length; i++) Near(inventory.playerStats.GetStat(stats[i]), baseline[i], names[i] + " removed");
            var beer = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/Beer.asset");
            Require(beer != null && beer.eItem == EItem.Beer, "original Beer asset");
            allItems.Add(EItem.Beer, beer);
            float baseHealth = inventory.playerStats.GetStat(EStat.MaxHealth);
            float baseDamage = inventory.playerStats.GetStat(EStat.DamageMultiplier);
            inventory.playerHealth = new PlayerHealth(inventory.playerStats);
            inventory.itemInventory.AddItem(EItem.Beer, 2); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MaxHealth), baseHealth * .9f, "two Beer stacks reduce health");
            Require(inventory.playerHealth.maxHp == (int)inventory.playerStats.GetStat(EStat.MaxHealth) && inventory.playerHealth.hp <= inventory.playerHealth.maxHp, $"Beer updates and clamps actual player health: hp={inventory.playerHealth.hp}, max={inventory.playerHealth.maxHp}, stat={inventory.playerStats.GetStat(EStat.MaxHealth)}");
            Near(inventory.playerStats.GetStat(EStat.DamageMultiplier), baseDamage + .4f, "two Beer stacks increase damage");
            Near((float)damageMethod.Invoke(null, new object[] { 100f, new StatComponents() }), 100f * (baseDamage + .4f), "Beer reaches weapon damage calculation");
            inventory.itemInventory.RemoveItem(EItem.Beer); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MaxHealth), baseHealth * .95f, "one Beer stack health");
            Near(inventory.playerStats.GetStat(EStat.DamageMultiplier), baseDamage + .2f, "one Beer stack damage");
            inventory.itemInventory.RemoveItem(EItem.Beer); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MaxHealth), baseHealth, "Beer removal restores health");
            Near(inventory.playerStats.GetStat(EStat.DamageMultiplier), baseDamage, "Beer removal restores damage");
            Require(inventory.playerHealth.maxHp == (int)baseHealth, "Beer removal restores actual maximum health");
            var socks = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/Turbo Socks.asset");
            Require(socks != null && socks.eItem == EItem.TurboSocks, "original Turbo Socks asset");
            allItems.Add(EItem.TurboSocks, socks);
            var movement = new PlayerMovementValues();
            movement.CreateMovement(root.AddComponent<Rigidbody>(), ECharacter.Fox);
            float baseSpeed = inventory.playerStats.GetStat(EStat.MoveSpeedMultiplier);
            Near(movement.GetMaxSpeed(), movement.maxRunSpeed * baseSpeed, "baseline maximum movement speed");
            inventory.itemInventory.AddItem(EItem.TurboSocks, 2); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MoveSpeedMultiplier), baseSpeed + .30f, "two Turbo Socks stacks");
            Near(movement.GetMaxSpeed(), movement.maxRunSpeed * (baseSpeed + .30f), "Turbo Socks reach maximum movement speed");
            inventory.itemInventory.RemoveItem(EItem.TurboSocks); inventory.playerStats.Tick();
            Near(movement.GetMaxSpeed(), movement.maxRunSpeed * (baseSpeed + .15f), "one Turbo Socks stack");
            inventory.itemInventory.RemoveItem(EItem.TurboSocks); inventory.playerStats.Tick();
            Near(movement.GetMaxSpeed(), movement.maxRunSpeed * baseSpeed, "Turbo Socks removal restores speed");
            var crystal = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/Leeching Crystal.asset");
            Require(crystal != null && crystal.eItem == EItem.LeechingCrystal, "original Leeching Crystal asset");
            allItems.Add(EItem.LeechingCrystal, crystal);
            float baseRegen = inventory.playerStats.GetStat(EStat.HealthRegen);
            inventory.itemInventory.AddItem(EItem.LeechingCrystal); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MaxHealth), baseHealth + 50f, "one Leeching Crystal increases maximum health");
            Near(inventory.playerStats.GetStat(EStat.HealthRegen), baseRegen * .5f, "one Leeching Crystal reduces regeneration");
            Require(inventory.playerHealth.maxHp == (int)(baseHealth + 50f), "Leeching Crystal updates player maximum health");
            inventory.itemInventory.AddItem(EItem.LeechingCrystal); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MaxHealth), baseHealth + 100f, "two Leeching Crystals increase maximum health");
            Near(inventory.playerStats.GetStat(EStat.HealthRegen), 0f, "two Leeching Crystals suppress regeneration");
            inventory.itemInventory.RemoveItem(EItem.LeechingCrystal); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.HealthRegen), baseRegen * .5f, "removing one Leeching Crystal restores half regeneration");
            inventory.itemInventory.RemoveItem(EItem.LeechingCrystal); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetStat(EStat.MaxHealth), baseHealth, "removing Leeching Crystal restores health stat");
            Near(inventory.playerStats.GetStat(EStat.HealthRegen), baseRegen, "removing Leeching Crystal restores regeneration");
            Require(inventory.playerHealth.maxHp == (int)baseHealth, "Leeching Crystal removal restores maximum health");
            var shield = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/Spiky Shield.asset");
            Require(shield != null && shield.eItem == EItem.SpikyShield, "original Spiky Shield asset");
            allItems.Add(EItem.SpikyShield, shield);
            float baseArmor = inventory.playerStats.GetRawStat(EStat.Armor), baseThorns = inventory.playerStats.GetRawStat(EStat.Thorns);
            MyTime.time = 100f;
            inventory.itemInventory.AddItem(EItem.SpikyShield); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Armor), baseArmor + .1f, "one Spiky Shield armor");
            MyTime.time = 100.99f; inventory.itemInventory.Tick(); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns, "Spiky Shield waits one second");
            MyTime.time = 101f; inventory.itemInventory.Tick(); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns + (baseArmor + .1f) * 200f, "one Spiky Shield retaliation");
            inventory.itemInventory.AddItem(EItem.SpikyShield); inventory.playerStats.Tick();
            MyTime.time = 102f; inventory.itemInventory.Tick(); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Armor), baseArmor + .2f, "two Spiky Shields armor");
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns + (baseArmor + .2f) * 400f, "two Spiky Shields retaliation");
            inventory.itemInventory.RemoveItem(EItem.SpikyShield); inventory.playerStats.Tick();
            MyTime.time = 103f; inventory.itemInventory.Tick(); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns + (baseArmor + .1f) * 200f, "one Spiky Shield after removal");
            inventory.itemInventory.RemoveItem(EItem.SpikyShield); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Armor), baseArmor, "Spiky Shield armor removed");
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns, "Spiky Shield retaliation removed");
            inventory.itemInventory.AddItem(EItem.SpikyShield); inventory.playerStats.Tick();
            MyTime.time = 104f; inventory.itemInventory.Tick(); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns + (baseArmor + .1f) * 200f, "reacquired Spiky Shield retaliation");
            inventory.itemInventory.RemoveItem(EItem.SpikyShield); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Thorns), baseThorns, "reacquired Spiky Shield removal");
            Debug.Log("SpikyShieldPortCheck passed: timed armor and retaliation, stacking and removal");
            var tonic = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/Grandma's Secret Tonic.asset");
            Require(tonic != null && tonic.eItem == EItem.GrandmasSecretTonic, "original Grandma's Secret Tonic asset");
            allItems.Add(EItem.GrandmasSecretTonic, tonic);
            float baseCrit = inventory.playerStats.GetRawStat(EStat.CritChance);
            inventory.itemInventory.AddItem(EItem.GrandmasSecretTonic, 2); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.CritChance), baseCrit + .02f, "two tonics add one fixed crit bonus");
            inventory.itemInventory.RemoveItem(EItem.GrandmasSecretTonic); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.CritChance), baseCrit + .02f, "one tonic retains crit bonus");
            inventory.itemInventory.RemoveItem(EItem.GrandmasSecretTonic); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.CritChance), baseCrit, "last tonic removal restores crit chance");
            inventory.itemInventory.AddItem(EItem.GrandmasSecretTonic); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.CritChance), baseCrit + .02f, "reacquired tonic restores crit bonus");
            inventory.itemInventory.RemoveItem(EItem.GrandmasSecretTonic); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.CritChance), baseCrit, "reacquired tonic removal restores crit chance");
            Debug.Log("GrandmasTonicStatRemovalCheck passed: stack, removal and reacquisition");
            var chonk = AssetDatabase.LoadAssetAtPath<ItemData>("Assets/MonoBehaviour/Chonkplate.asset");
            Require(chonk != null && chonk.eItem == EItem.Chonkplate, "original Chonkplate asset");
            allItems.Add(EItem.Chonkplate, chonk);
            float baseOverheal = inventory.playerStats.GetRawStat(EStat.Overheal);
            float baseLifesteal = inventory.playerStats.GetRawStat(EStat.Lifesteal);
            inventory.itemInventory.AddItem(EItem.Chonkplate, 2); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Overheal), baseOverheal + 1.5f, "two Chonkplate overheal");
            Near(inventory.playerStats.GetRawStat(EStat.Lifesteal), baseLifesteal + .4f, "two Chonkplate lifesteal");
            Require(inventory.playerHealth.maxOverheal == (int)(inventory.playerHealth.maxHp * inventory.playerStats.GetStat(EStat.Overheal)), "Chonkplate updates overheal capacity");
            inventory.itemInventory.AddItem(EItem.Chonkplate, 3); inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Lifesteal), baseLifesteal + 1f, "five Chonkplate lifesteal");
            var health = inventory.playerHealth; health.hp = health.maxHp - 10; health.overheal = 0;
            Enemy.A_Damage?.Invoke(null, new DamageContainer(0f, "controlled hit") { damage = 1 }); health.Tick();
            Require(health.hp == health.maxHp - 9, "weapon hit heals from Chonkplate lifesteal");
            health.hp = health.maxHp; health.overheal = 0;
            Enemy.A_Damage?.Invoke(null, new DamageContainer(0f, "controlled hit") { damage = 1 }); health.Tick();
            Require(health.overheal > .9f && health.overheal <= 1f, "lifesteal can add overheal at full health");
            int priorHp = health.hp; float priorOverheal = health.overheal;
            Enemy.A_Damage?.Invoke(null, new DamageContainer(0f, "bloodmark") { damage = 1, damageEffect = EDamageEffect.Bloodmark }); health.Tick();
            Require(health.hp == priorHp && health.overheal <= priorOverheal, "bloodmark damage does not lifesteal");
            health.overheal = 50;
            for (int i = 0; i < 5; i++) inventory.itemInventory.RemoveItem(EItem.Chonkplate);
            inventory.playerStats.Tick();
            Near(inventory.playerStats.GetRawStat(EStat.Overheal), baseOverheal, "Chonkplate overheal removed");
            Near(inventory.playerStats.GetRawStat(EStat.Lifesteal), baseLifesteal, "Chonkplate lifesteal removed");
            Require(health.maxOverheal == (int)(health.maxHp * inventory.playerStats.GetStat(EStat.Overheal)), "removal updates maximum overheal");
            Near(health.overheal, 50, "overheal remains until next health tick");
            health.Tick(); Require(health.overheal <= health.maxOverheal, "next health tick clamps overheal to reduced cap");
            Debug.Log("ChonkplatePortCheck passed: stacks, capacity, controlled hit healing, overheal and removal");
            Debug.Log("LeechingCrystalPortCheck passed: inventory stacks, health, regeneration and removal");
            Debug.Log("BasicStatItemsPortCheck passed: original items, stacked stats, Beer damage and health tradeoff, removal and weapon calculation");
        }
        finally { MyTime.time = oldTime; inventory.playerHealth?.OnDestroy(); inventory.playerStats.OnDestroy(); inventory.statusEffects.OnDestroy(); inventory.itemInventory.Cleanup(); UnityEngine.Object.DestroyImmediate(root); MyPlayer.Instance = null; GameManager.Instance = null; DataManager.Instance = null; }
    }
}
